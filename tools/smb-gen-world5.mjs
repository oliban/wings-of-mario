#!/usr/bin/env node
// Generate world 5's level modules from the original's own area data.
//   node tools/smb-gen-world5.mjs
//
// Same rules as the world-1 and world-2 generators: every position comes from
// reference/, not from anyone's memory of the game, and deviations are marked
// DEVIATION and exist only where this engine lacks a mechanism the original had.
//
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  emitLevel,
  bonusRoomSource,
  skyAreaSource,
  bonusPagesFor,
  bonusReturn,
  skyReturn,
  waterReturn,
  waterRoomSource,
} from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');


const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. Item blocks are otherwise left
// exactly where the original puts them.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}

// Spawn on the first column with two clear rows above solid ground, scanning
// from row 13 — the standard floor — upward.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 13; y >= 3; y--) {
      const solid = SOLID.has(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}

// Podoboos leap out of the surface of the lava, so seat them on it.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}

// A column with floor under it and two clear rows above, for a warp to land in.
function landingNear(rows, want) {
  for (let d = 0; d < 40; d++) {
    for (const x of [want + d, want - d]) {
      if (x < 2 || x >= rows[0].length) continue;
      if (SOLID.has(rows[13][x]) && rows[12][x] === '.' && rows[11][x] === '.') return x;
    }
  }
  return want;
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');
const contentsBlock = (cs) =>
  cs.map((c) => `    ${j(c).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world5.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns and heights, hole widths, block rows,
// the staircases, the flagpole and the castle are the original's own numbers,
// not an approximation of them. Re-run the generator rather than editing by
// hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}


// ---------------------------------------------------------------------- 5-1
{
  const L = emitLevel('5-1', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const wp = L.meta.warpPipe;
  const back = bonusReturn(L.meta, 5, bonusPagesFor('5-1')[0]) || { col: landingNear(rows, wp.x + 20), top: 12 };
  const body = `
${bonusRoomSource('5-1b', 'WORLD 5-1', bonusPagesFor('5-1')[0], back.col, back.top)}
export default {
  id: '5-1',
  name: 'WORLD 5-1',
  time: 400,
  theme: 'overworld',
  scenery: 'snow',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '5-1b', x: 3.5, y: 3, exit: 'down' } },
  ],
  areas: { '5-1b': BONUS },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '5-1.js'),
    header(
      '5-1 — overworld, the cannons',
      '// Area style 2: the AreaStyleObjects here are BULLET BILL CANNONS, not ledges.\n' +
        '//\n' +
        "// The header's low three bits are 5, which is 4 or more, so it sets\n" +
        '// BackgroundColorCtrl rather than ForegroundScenery. Control 5 selects\n' +
        '// DaySnowPaletteData: the sky stays the ordinary blue ($22) and only the\n' +
        '// foliage palette changes, to white. Our sky is therefore correct already;\n' +
        '// the white bushes are the queued tile-palette work.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 5-2
{
  const L = emitLevel('5-2', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const wp = L.meta.warpPipe;
  const vine = L.meta.vine;
  // The return column is DATA, not a search: WaterArea1's own row-$0e record
  // names EntrancePage 7 for world 5, column 115, and a pipe is standing at 115.
  // landingNear walked past it to bare floor, so the exit played a pipe
  // emergence in thin air.
  const out = waterReturn(L.meta, 5) || { col: landingNear(rows, wp.x + 26), top: 12 };
  const body = `
${waterRoomSource('5-2b', 'WORLD 5-2', out.col, out.top)}
${skyAreaSource('5-2c', 'WORLD 5-2', skyReturn(5, 'GroundArea12'))}
export default {
  id: '5-2',
  name: 'WORLD 5-2',
  time: 400,
  theme: 'overworld',
  scenery: 'snow',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
    { x: ${vine.x}, y: ${vine.y}, item: 'vine', height: 11, warp: { to: { area: '5-2c', x: 3.5, y: 12, exit: 'none' } } },
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '5-2b', x: 2.5, y: 0, exit: 'none' } },
  ],
  areas: { '5-2b': WATERROOM, '5-2c': SKY },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '5-2.js'),
    header(
      '5-2 — overworld, the cannons',
      '// Cannons again (area style 2), plus a beanstalk at ' + vine.x + ' into coin heaven and\n' +
        '// a pipe at ' + wp.x + ' into the underwater bonus room. This level names no coin\n' +
        '// room at all — the page-0 one it used to get was my default, not its data.\n' +
        '// A\n' +
        '// jumpspring at ' + (L.meta.springs[0] ? L.meta.springs[0].x : '-') + ' and nine holes. Day-snow colour control, as 5-1.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 5-3
{
  const L = emitLevel('5-3', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '5-3',
  name: 'WORLD 5-3',
  time: 300,
  theme: 'athletic',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '5-3.js'),
    header(
      '5-3 — the tree tops',
      '// GroundArea7 — the SAME area as 1-3, tile for tile. The two levels differ only\n' +
        '// in their enemy streams, which is why this one has a bullet-bill frenzy and a\n' +
        '// vertical lift where 1-3 has neither. A useful check that the pipeline is\n' +
        '// deterministic: if 5-3 and 1-3 ever stop matching, something has gone wrong.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 5-4
{
  const L = emitLevel('5-4', { theme: 'castle' });
  const ents = L.entities.slice();
  const rows = seatPodoboos(relieveBlocks(L.rows), ents);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '5-4',
  name: 'WORLD 5-4',
  time: 300,
  theme: 'castle',
  music: 'castle',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(ents)}
  ],
  flagpole: null,
  castle: { x: ${L.width - 6}, tall: true },
};
`;
  writeFileSync(
    join(OUT, '5-4.js'),
    header(
      '5-4 — castle',
      '// CastleArea3 — the SAME area as 2-4, tile for tile, down to the rope shaft and\n' +
        '// its two small lifts. Only the enemy stream differs: this one adds a long\n' +
        '// firebar ($1f) and a second short one that 2-4 does not have.'
    ) +
      tilesBlock(rows) +
      body
  );
}

console.log('regenerated 5-1, 5-2, 5-3, 5-4 from reference data');
