#!/usr/bin/env node
// Generate world 4's level modules from the original's own area data.
//   node tools/smb-gen-world4.mjs
//
// Same rules as the world-1 and world-2 generators: every position comes from
// reference/, not from anyone's memory of the game, and deviations are marked
// DEVIATION and exist only where this engine lacks a mechanism the original had.
//
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  emitLevel,
  bonusRoomSource,
  skyAreaSource,
  bonusPagesFor,
  bonusReturn,
  buildArea,
  warpZoneSource,
} from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');

const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. Item blocks are otherwise left
// exactly where the original puts them.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}

// Spawn on the first column with two clear rows above solid ground, scanning
// from row 13 — the standard floor — upward.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 13; y >= 3; y--) {
      const solid = SOLID.has(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}

// Podoboos leap out of the surface of the lava, so seat them on it.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}

// A column with floor under it and two clear rows above, for a warp to land in.
function landingNear(rows, want) {
  for (let d = 0; d < 40; d++) {
    for (const x of [want + d, want - d]) {
      if (x < 2 || x >= rows[0].length) continue;
      if (SOLID.has(rows[13][x]) && rows[12][x] === '.' && rows[11][x] === '.') return x;
    }
  }
  return want;
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');
const contentsBlock = (cs) =>
  cs.map((c) => `    ${j(c).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world4.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns and heights, hole widths, block rows,
// the staircases, the flagpole and the castle are the original's own numbers,
// not an approximation of them. Re-run the generator rather than editing by
// hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}


// ---------------------------------------------------------------------- 4-1
{
  const L = emitLevel('4-1', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const wp = L.meta.warpPipe;
  const out = bonusReturn(L.meta, 4, 6) || { col: landingNear(rows, wp.x + 34), top: 12 };
  const body = `
${bonusRoomSource('4-1b', 'WORLD 4-1', 6, out.col, out.top)}
export default {
  id: '4-1',
  name: 'WORLD 4-1',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '4-1b', x: 3.5, y: 3, exit: 'down' } },
  ],
  areas: { '4-1b': BONUS },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '4-1.js'),
    header(
      '4-1 — overworld',
      "// Lakitu's level: the only hand-placed enemy in the whole area is one Lakitu,\n" +
        '// and everything else you fight is the spiny he throws. The warp pipe at ' + wp.x + '\n' +
        "// drops into UndergroundArea3 page 6, which is the room this level's own\n" +
        '// enemy stream names.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 4-2
{
  const L = emitLevel('4-2', { theme: 'underground' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const side = L.meta.sidePipes[0];
  const vine = L.meta.vine;
  const wps = L.meta.pipes.filter((p) => p.warp);
  const wp = wps[0];
  // The second warp pipe sits in a box sealed off by solid terrain on both
  // sides — the room you reach by running along the very top of the level,
  // which is exactly how the original hides 4-2's warp zone.
  const secret = wps[wps.length - 1];
  const out = bonusReturn(L.meta, 4, 8) || { col: landingNear(rows, wp.x + 30), top: 12 };

  const body = `
${bonusRoomSource('4-2b', 'WORLD 4-2', 8, out.col, out.top)}
${warpZoneSource('4-2c', 'WORLD 4-2', [null, '5-1', null])}
${warpZoneSource('4-2w', 'WORLD 4-2', ['8-1', '7-1', '6-1']).replace('WARPZONE', 'WARPZONE2')}
export default {
  id: '4-2',
  name: 'WORLD 4-2',
  time: 400,
  theme: 'underground',
  music: 'underground',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
    { x: ${vine.x}, y: ${vine.y}, item: 'vine', height: 11, warp: { to: { area: '4-2c', x: 2.5, y: 12, exit: 'none' } } },
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '4-2b', x: 3.5, y: 3, exit: 'down' } },
    { from: { x: ${side.x}, y: ${side.top} }, dir: 'right', to: { complete: true } },
    { from: { x: ${secret.x}, y: ${secret.top} }, dir: 'down', to: { area: '4-2w', x: 2.5, y: 12, exit: 'down' } },
  ],
  areas: { '4-2b': BONUS, '4-2c': WARPZONE, '4-2w': WARPZONE2 },
};
`;
  writeFileSync(
    join(OUT, '4-2.js'),
    header(
      '4-2 — underground',
      '// The level with two ways out. The beanstalk at ' + vine.x + ' climbs to coin heaven,\n' +
        '// and the pipe at the end of THAT is the original\'s warp to world 5. The\n' +
        '// sideways exit pipe at ' + side.x + ' leads to the warp zone, which is its own area in\n' +
        '// the data (GroundArea16, pointer $2f) rather than a strip of this level.\n' +
        '//\n' +
        "// DEVIATION: in the original that pipe opens the warp zone — its own area,\n" +
        '// GroundArea16 at pointer $2f, whose three pipes are worlds 6, 7 and 8. None\n' +
        '// of those worlds exist yet, so the pipe simply finishes the level instead,\n' +
        '// the way 2-2 ends at its own. The beanstalk route to world 5 is real.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 4-3
{
  const L = emitLevel('4-3', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '4-3',
  name: 'WORLD 4-3',
  time: 300,
  theme: 'athletic',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '4-3.js'),
    header(
      '4-3 — the mushrooms',
      '// The area style here is 1, not 0: these are MUSHROOM ledges, not tree ledges.\n' +
        '// A mushroom grows a single stem under its middle column where a tree grows a\n' +
        '// trunk under every column, which is the whole visual difference between this\n' +
        '// level and 1-3. Four balance pairs and a vertical lift carry you between them.'
    ) +
      tilesBlock(rows) +
      body
  );
}

// ---------------------------------------------------------------------- 4-4
{
  const L = emitLevel('4-4', { theme: 'castle' });
  const ents = L.entities.slice();
  const rows = seatPodoboos(relieveBlocks(L.rows), ents);
  const sp = findSpawn(rows);
  // The page-9 wall the two upper corridors run into.
  const wall = 144;
  const body = `
export default {
  id: '4-4',
  name: 'WORLD 4-4',
  // 400, not 300: the area header's top two bits are the GameTimerSetting
  // (asm:4415-4423) and index GameTimerData = 400/300/200 (asm:2828-2831).
  // CastleArea2/5/6 all carry header0 $5b -> setting 1 -> 400. These are the
  // loop mazes, the longest levels in the game to solve, and they were the
  // only three in the game running TIGHTER than the original.
  time: 400,
  theme: 'castle',
  music: 'castle',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(ents)}
  ],
  warps: [
    // ProcLoopCommand, as close as this engine can get it. Both upper corridors
    // dead-end against the wall at column ${wall}, which is the start of page 9 —
    // the page whose LoopCmdYPosition entry is $b0, meaning you were supposed to
    // be on the FLOOR here. Running into either dead end sends you back four
    // pages, exactly as ExecGameLoopback does. Without this the wrong corridor
    // is a permanent trap rather than a mistake you pay for.
    { from: { x: ${wall}, y: 5 }, dir: 'right', to: { area: 'main', x: ${wall - 64}.5, y: 12, exit: 'none' } },
    { from: { x: ${wall}, y: 9 }, dir: 'right', to: { area: 'main', x: ${wall - 64}.5, y: 12, exit: 'none' } },
  ],
  flagpole: null,
  castle: { x: ${L.width - 6}, tall: true },
};
`;
  writeFileSync(
    join(OUT, '4-4.js'),
    header(
      '4-4 — the maze castle',
      '// DEVIATION, and the only real one in world 4: this is the first level whose\n' +
        '// LoopCmd objects (columns 76 and 140) actually mean something, and we cannot\n' +
        '// honour them yet.\n' +
        '//\n' +
        '// LoopCmdE is `rts` — the object renders nothing. The maze lives in\n' +
        '// ProcLoopCommand, which checks three parallel tables when the player reaches\n' +
        '// the page: LoopCmdWorldNumber, LoopCmdPageNumber and LoopCmdYPosition. For\n' +
        '// world 4 the entries are page 5 at Y $40 and page 9 at Y $b0, and the player\n' +
        '// must also be in state 0, on the ground. Take the wrong height and\n' +
        '// ExecGameLoopback sends you back FOUR PAGES. Our engine has no such trigger,\n' +
        '// so the geometry is faithful but the maze does not loop — you can simply walk\n' +
        '// through. Everything else, Bowser and the axe at ' + L.meta.axe.x + ' included, is the\n' +
        "// original's."
    ) +
      tilesBlock(rows) +
      body
  );
}

console.log('regenerated 4-1, 4-2, 4-3, 4-4 from reference data');
