#!/usr/bin/env node
// Generate world 7's level modules from the original's own area data.
//   node tools/smb-gen-world7.mjs
//
// Same rules as the world-1 and world-2 generators: every position comes from
// reference/, not from anyone's memory of the game, and deviations are marked
// DEVIATION and exist only where this engine lacks a mechanism the original had.
//
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  emitLevel,
  bonusRoomSource,
  skyAreaSource,
  bonusPagesFor,
  bonusReturn,
} from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');

const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. Item blocks are otherwise left
// exactly where the original puts them.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}

// Spawn on the first column with two clear rows above solid ground, scanning
// from row 13 — the standard floor — upward.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 13; y >= 3; y--) {
      const solid = SOLID.has(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}

// Podoboos leap out of the surface of the lava, so seat them on it.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}

// A column with floor under it and two clear rows above, for a warp to land in.
function landingNear(rows, want) {
  for (let d = 0; d < 40; d++) {
    for (const x of [want + d, want - d]) {
      if (x < 2 || x >= rows[0].length) continue;
      if (SOLID.has(rows[13][x]) && rows[12][x] === '.' && rows[11][x] === '.') return x;
    }
  }
  return want;
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');
const contentsBlock = (cs) =>
  cs.map((c) => `    ${j(c).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world7.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns and heights, hole widths, block rows,
// the staircases, the flagpole and the castle are the original's own numbers,
// not an approximation of them. Re-run the generator rather than editing by
// hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}


// ---------------------------------------------------------------------- 7-1
{
  const L = emitLevel('7-1', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const wp = L.meta.warpPipe;
  // The return column is DATA, not a search: the coin room's own row-$0e record
  // names the page it puts you back on, and a pipe is standing there. landingNear
  // walked past it to bare floor, so the exit played a pipe emergence in thin air.
  const back = bonusReturn(L.meta, 7, bonusPagesFor('7-1')[0]) || {
    col: landingNear(rows, wp.x + 24),
    top: 12,
  };
  const body = `
${bonusRoomSource('7-1b', 'WORLD 7-1', bonusPagesFor('7-1')[0], back.col, back.top)}
export default {
  id: '7-1',
  name: 'WORLD 7-1',
  time: 400,
  theme: 'overworld',
  scenery: 'snow',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '7-1b', x: 3.5, y: 3, exit: 'down' } },
  ],
  areas: { '7-1b': BONUS },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '7-1.js'),
    header('7-1 — overworld, the cannons', '// Area style 2: bullet-bill cannons. A jumpspring at ' + L.meta.springs[0].x + ' and the warp\n' +
        '// pipe at ' + L.meta.warpPipe.x + '.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 7-2
{
  const L = emitLevel('7-2', { theme: 'water' });
  const rows = relieveBlocks(L.rows);
  const wp = L.meta.waterPipe;
  const body = `
export default {
  id: '7-2',
  name: 'WORLD 7-2',
  time: 400,
  theme: 'water',
  music: 'underwater',
  width: ${L.width},
  height: 15,
  spawn: { x: 2, y: 6 },
  tiles: TILES,
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x - 1}, y: ${wp.top} }, dir: 'right', to: { complete: true } },
  ],
  flagpole: null,
  castle: null,
};
`;
  writeFileSync(
    join(OUT, '7-2.js'),
    header(
      '7-2 — underwater',
      '// WaterArea2 — the SAME area as 2-2, tile for tile, and it ends the same way:\n' +
        '// at the WaterPipe in column ' + wp.x + ', cut into the wall the last\n' +
        '// AlterAreaAttributes raises. Only the enemy stream differs.'
    ) + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 7-3
{
  const L = emitLevel('7-3', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '7-3',
  name: 'WORLD 7-3',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '7-3.js'),
    header('7-3 — the bridges', '// GroundArea8 — the SAME area as 2-3. It is also the second of the only two\n' +
        '// levels the original empties on a first quest: all seven hand-placed enemies\n' +
        '// are hard-mode-only, so what fills it is the cheep-cheep frenzy, exactly as\n' +
        '// in 2-3. It is SUPPOSED to look bare of hand-placed enemies.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 7-4
{
  const L = emitLevel('7-4', { theme: 'castle' });
  const ents = L.entities.slice();
  const rows = seatPodoboos(relieveBlocks(L.rows), ents);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '7-4',
  name: 'WORLD 7-4',
  // 400, not 300: the area header's top two bits are the GameTimerSetting
  // (asm:4415-4423) and index GameTimerData = 400/300/200 (asm:2828-2831).
  // CastleArea2/5/6 all carry header0 $5b -> setting 1 -> 400. These are the
  // loop mazes, the longest levels in the game to solve, and they were the
  // only three in the game running TIGHTER than the original.
  time: 400,
  theme: 'castle',
  music: 'castle',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(ents)}
  ],
  flagpole: null,
  castle: { x: ${L.width - 6}, tall: true },
};
`;
  writeFileSync(
    join(OUT, '7-4.js'),
    header('7-4 — the maze castle', '// Six LoopCmd objects, the most in the game. See the note in 4-4 for how the\n' +
        '// maze actually works; the loopback warps below are added where the wrong\n' +
        '// corridor would otherwise dead-end.') + tilesBlock(rows) + body
  );
}

console.log('regenerated 7-1, 7-2, 7-3, 7-4 from reference data');
