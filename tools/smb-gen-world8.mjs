#!/usr/bin/env node
// Generate world 8's level modules from the original's own area data.
//   node tools/smb-gen-world8.mjs
//
// Same rules as the world-1 and world-2 generators: every position comes from
// reference/, not from anyone's memory of the game, and deviations are marked
// DEVIATION and exist only where this engine lacks a mechanism the original had.
//
import { writeFileSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePointers } from './smb-decode.mjs';
import {
  emitLevel,
  bonusRoomSource,
  skyAreaSource,
  bonusPagesFor,
  bonusReturn,
  buildArea,
} from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');


const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

const REF = JSON.parse(readFileSync(join(ROOT, 'reference', 'smb-areas.json'), 'utf8'));

// The row-$0e records of a level's own enemy stream, in stream order: where a
// pipe entered near that column sends you, and at which page you come out.
function pointersIn(areaName) {
  return decodePointers(REF.areas[areaName].enemyBytes);
}
function pointersFor(levelId) {
  return pointersIn(REF.levelMap[levelId].area);
}

// World 8's three loop commands (LoopCmdWorldNumber/LoopCmdPageNumber,
// smbdis.asm:7787-7793): pages 6, 11 and 16. Their LoopCmdYPosition is $f0,
// which no player can ever be at, so the "correct position" test can never pass
// and ExecGameLoopback always fires — that is what makes 8-4's rooms inescapable
// except through the right pipe. The loopback sends the player back four pages.
const LOOP_PAGES = [6, 11, 16];
const LOOP_BACK_PAGES = 4;
// ProcLoopCommand fires on CurrentColumnPos == 0, and CurrentPageLoc tracks the
// column being rendered, which runs about nine columns ahead of the player. So
// the player is roughly nine columns short of the page boundary when the loop
// takes them. This engine has no rendering pointer to hang the trigger off, so
// it goes on the column the player is actually standing on when it fires.
const LOOP_LEAD = 9;

// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. Item blocks are otherwise left
// exactly where the original puts them.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}

// Spawn on the first column with two clear rows above solid ground, scanning
// from row 13 — the standard floor — upward.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 13; y >= 3; y--) {
      const solid = SOLID.has(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}

// Podoboos leap out of the surface of the lava, so seat them on it.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}

// A column with floor under it and two clear rows above, for a warp to land in.
function landingNear(rows, want) {
  for (let d = 0; d < 40; d++) {
    for (const x of [want + d, want - d]) {
      if (x < 2 || x >= rows[0].length) continue;
      if (SOLID.has(rows[13][x]) && rows[12][x] === '.' && rows[11][x] === '.') return x;
    }
  }
  return want;
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');
const contentsBlock = (cs) =>
  cs.map((c) => `    ${j(c).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world8.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns and heights, hole widths, block rows,
// the staircases, the flagpole and the castle are the original's own numbers,
// not an approximation of them. Re-run the generator rather than editing by
// hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}


// ---------------------------------------------------------------------- 8-1
{
  const L = emitLevel('8-1', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const wp = L.meta.warpPipe;
  const back = bonusReturn(L.meta, 8, bonusPagesFor('8-1')[0]) || { col: landingNear(rows, wp.x + 24), top: 12 };
  const body = `
${bonusRoomSource('8-1b', 'WORLD 8-1', bonusPagesFor('8-1')[0], back.col, back.top)}
export default {
  id: '8-1',
  name: 'WORLD 8-1',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '8-1b', x: 3.5, y: 12, exit: 'down' } },
  ],
  areas: { '8-1b': BONUS },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '8-1.js'),
    header('8-1 — overworld, the long one', '// The longest level in the game at ' + L.width + ' columns — nearly twice 1-1. Eleven\n' +
        '// pipes and a warp pipe at ' + L.meta.warpPipe.x + '.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 8-2
{
  const L = emitLevel('8-2', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const wp = L.meta.warpPipe;
  const back = bonusReturn(L.meta, 8, bonusPagesFor('8-2')[0]) || { col: landingNear(rows, wp.x + 24), top: 12 };
  const body = `
${bonusRoomSource('8-2b', 'WORLD 8-2', bonusPagesFor('8-2')[0], back.col, back.top)}
export default {
  id: '8-2',
  name: 'WORLD 8-2',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wp.x}, y: ${wp.top} }, dir: 'down', to: { area: '8-2b', x: 3.5, y: 3, exit: 'down' } },
  ],
  areas: { '8-2b': BONUS },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '8-2.js'),
    header('8-2 — overworld, the cannons', '// Cannons (area style 2), a jumpspring at ' + L.meta.springs[0].x + ', and the warp pipe\n' +
        '// at ' + L.meta.warpPipe.x + '.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 8-3
{
  const L = emitLevel('8-3', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '8-3',
  name: 'WORLD 8-3',
  time: 400,
  theme: 'overworld',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '8-3.js'),
    header('8-3 — overworld, the cannons', '// Cannons again, and the last daylight in the game: hammer bros and a run of\n' +
        '// pipes, then the final castle.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 8-4
{
  const L = emitLevel('8-4', { theme: 'castle' });
  const ents = L.entities.slice();
  const rows = seatPodoboos(relieveBlocks(L.rows), ents);
  const sp = findSpawn(rows);
  // 8-4 is four rooms separated by lava too wide to jump; the pipes are the
  // route, and taking the wrong one sends you back to the start. Where each pipe
  // goes is not guesswork: the level's own enemy stream carries row-$0e records
  // holding an area pointer and an ENTRANCE PAGE, and one such record sits a few
  // columns past every warp pipe. ProcessEnemyData reads a record when the
  // screen's right edge reaches it — about nine columns ahead of the player — so
  // the record governing a pipe is the last one at or before pipe + 9.
  const ptrs = pointersFor('8-4');
  const govern = (col) => {
    let best = null;
    for (const p of ptrs) if (p.x <= col + 9) best = p;
    return best;
  };
  // Area pointer 0x02 is WaterArea3 (area type 0, index 2); everything else in
  // this stream points back at CastleArea6, i.e. at 8-4 itself.
  const isWater = (p) => (p.pointer & 0x60) === 0x00;
  const wps = L.meta.pipes.filter((p) => p.warp);
  const water = buildArea('WaterArea3', { theme: 'water' });
  const wrows = water.tiles.map((r) => {
    // Flood the open cells, as every water level does.
    let out = '';
    for (let x = 0; x < water.width; x++) out += r[x] === '.' ? '_' : r[x];
    return out;
  });
  const wpipe = water.meta.waterPipe;
  // Where the water section puts you back is its own row-$0e record, not a guess:
  // WaterArea3 carries one record, pointing at CastleArea6 with entrance page 16.
  const wback = pointersIn('WaterArea3');
  const wcol = landingNear(rows, wback[0].entrancePage * 16);

  // The surface a walker is standing on at column x, and the row their feet are
  // on top of.
  const standRow = (x) => {
    for (let y = 3; y < rows.length; y++) if (SOLID.has(rows[y][x])) return y - 1;
    return 12;
  };
  const loops = LOOP_PAGES.map((pg) => {
    const at = pg * 16 - LOOP_LEAD;
    return { at, y: standRow(at), back: landingNear(rows, (pg - LOOP_BACK_PAGES) * 16) };
  });

  const body = `
// The underwater section, rendered from WaterArea3. You drop in at the left and
// swim right; the water pipe at column ${wpipe.x} is this area's only row-$0e record,
// and it points back at 8-4 with entrance page ${wback[0].entrancePage} — column ${wback[0].entrancePage * 16}, the last
// stretch of castle, with Bowser's bridge ahead of you and the third loop behind.
const WATER = {
  id: '8-4w',
  name: 'WORLD 8-4',
  theme: 'water',
  music: 'underwater',
  width: ${water.width},
  height: 15,
  spawn: { x: 5, y: 8 },
  tiles: [
${wrows.map((r) => `    '${r}',`).join('\n')}
  ],
  entities: [
${entsBlock(water.entities.map((e) => { const [type, variant] = e.type.split(':'); const { type: _t, ...rest } = e; return variant ? { type, ...rest, variant } : { type, ...rest }; }))}
  ],
  warps: [
    { from: { x: ${wpipe.x - 1}, y: ${wpipe.top} }, dir: 'right', to: { area: 'main', x: ${wcol}.5, y: ${standRow(wcol)}, exit: 'none' } },
  ],
};

export default {
  id: '8-4',
  name: 'WORLD 8-4',
  time: 300,
  theme: 'castle',
  music: 'castle',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(ents)}
  ],
  warps: [
${wps.map((p) => {
    const g = govern(p.x);
    if (isWater(g)) {
      return `    // record at ${g.x}: WaterArea3\n    { from: { x: ${p.x}, y: ${p.top} }, dir: 'down', to: { area: '8-4w', x: 5.5, y: 8, exit: 'down' } },`;
    }
    const col = landingNear(rows, g.entrancePage * 16);
    return `    // record at ${g.x}: 8-4 page ${g.entrancePage}\n    { from: { x: ${p.x}, y: ${p.top} }, dir: 'down', to: { area: 'main', x: ${col}.5, y: ${standRow(col)}, exit: 'none' } },`;
  }).join('\n')}
    // The three loop commands. Walk to the end of a room without taking its pipe
    // and the original loops the level data back four pages — the same corridor
    // again — and kills every enemy on the way. Modelled here as a silent warp
    // back to the page the loopback lands on.
${loops.map((l) => `    { from: { x: ${l.at}, y: ${l.y} }, dir: 'right', to: { area: 'main', x: ${l.back}.5, y: ${standRow(l.back)}, exit: 'none' } },`).join('\n')}
  ],
  areas: { '8-4w': WATER },
  flagpole: null,
  castle: { x: ${L.width - 6}, tall: true },
};
`;
  writeFileSync(
    join(OUT, '8-4.js'),
    header('8-4 — the final castle', '// The end of the game: ' + L.width + ' columns, fifteen pipes, three LoopCmds and the\n' +
        '// real Bowser. The axe is at ' + L.meta.axe.x + '.') + tilesBlock(rows) + body
  );
}

console.log('regenerated 8-1, 8-2, 8-3, 8-4 from reference data');
