#!/usr/bin/env node
// Generate world 6's level modules from the original's own area data.
//   node tools/smb-gen-world6.mjs
//
// Same rules as the world-1 and world-2 generators: every position comes from
// reference/, not from anyone's memory of the game, and deviations are marked
// DEVIATION and exist only where this engine lacks a mechanism the original had.
//
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  emitLevel,
  bonusRoomSource,
  skyAreaSource,
  bonusPagesFor,
  bonusReturn,
  skyReturn,
  waterReturn,
  waterRoomSource,
} from './smb-build.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'data', 'levels');

const SOLID = new Set(['#', 'B', '=', 'S', 'U']);

// DEVIATION: the original lets a power-up slide out sideways from a block set
// into a ceiling; this engine emerges it upward and would bury it. One tile of
// air is carved above any capped item block. Item blocks are otherwise left
// exactly where the original puts them.
function relieveBlocks(rows) {
  const CAPPED = new Set(['?', 'M']);
  const g = rows.map((r) => r.split(''));
  for (let y = 1; y < g.length; y++) {
    for (let x = 0; x < g[y].length; x++) {
      if (CAPPED.has(g[y][x]) && SOLID.has(g[y - 1][x])) g[y - 1][x] = '.';
    }
  }
  return g.map((r) => r.join(''));
}

// Spawn on the first column with two clear rows above solid ground, scanning
// from row 13 — the standard floor — upward.
function findSpawn(rows) {
  for (let x = 2; x < 30; x++) {
    for (let y = 13; y >= 3; y--) {
      const solid = SOLID.has(rows[y][x]);
      const clear = rows[y - 1][x] === '.' && rows[y - 2][x] === '.';
      if (solid && clear) return { x, y: y - 1 };
    }
  }
  return { x: 2, y: 12 };
}

// Podoboos leap out of the surface of the lava, so seat them on it.
function seatPodoboos(rows, ents) {
  const g = rows.map((r) => r.split(''));
  for (const e of ents) {
    if (e.type !== 'podoboo') continue;
    let top = g.length - 1;
    for (let y = 0; y < g.length; y++) {
      if (g[y][e.x] === 'L') { top = y; break; }
    }
    e.y = top;
  }
  return g.map((r) => r.join(''));
}

// A column with floor under it and two clear rows above, for a warp to land in.
function landingNear(rows, want) {
  for (let d = 0; d < 40; d++) {
    for (const x of [want + d, want - d]) {
      if (x < 2 || x >= rows[0].length) continue;
      if (SOLID.has(rows[13][x]) && rows[12][x] === '.' && rows[11][x] === '.') return x;
    }
  }
  return want;
}

const j = (v) => JSON.stringify(v);
const tilesBlock = (rows) => 'const TILES = [\n' + rows.map((r) => `  '${r}',\n`).join('') + '];\n';
const entsBlock = (ents) =>
  ents.map((e) => `    ${j(e).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');
const contentsBlock = (cs) =>
  cs.map((c) => `    ${j(c).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/"/g, "'")},`).join('\n');

function header(id, note) {
  return `// ---------------------------------------------------------------------------
// WORLD ${id}
//
// Generated by tools/smb-gen-world6.mjs from the original's area data — see
// reference/smb-areas.json. Pipe columns and heights, hole widths, block rows,
// the staircases, the flagpole and the castle are the original's own numbers,
// not an approximation of them. Re-run the generator rather than editing by
// hand.
//
${note}
// ---------------------------------------------------------------------------

`;
}


// ---------------------------------------------------------------------- 6-1
{
  const L = emitLevel('6-1', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '6-1',
  name: 'WORLD 6-1',
  time: 400,
  theme: 'overworld',
  sky: 'night',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '6-1.js'),
    header('6-1 — overworld', '// A NIGHT level, and one I missed the first time: an AlterAreaAttributes at\n' +
        '// column 6 sets colour control 4, which is black sky with no palette write —\n' +
        '// so the foliage stays green, exactly as in 3-3.\n' +
        '//\n' +
        '// Otherwise plain and fast: one pipe, one staircase, and the original leans\n' +
        '// on its koopas rather than on geometry.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 6-2
{
  const L = emitLevel('6-2', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  // Four destinations, four consumers, matched in the order the enemy stream
  // names them: pipe 19 -> coin room page 8, pipe 56 -> the water room,
  // beanstalk 81 -> coin heaven, pipe 153 -> coin room page 6.
  const wps = L.meta.pipes.filter((p) => p.warp);
  const pages = bonusPagesFor('6-2');
  // The return column is DATA, not a search: each coin room's own row-$0e record
  // names the page it puts you back on, and a pipe is standing there. landingNear
  // walked past it to bare floor, so the exit played a pipe emergence in thin air.
  const back = bonusReturn(L.meta, 6, pages[0]) || { col: landingNear(rows, wps[0].x + 24), top: 12 };
  const back2 = bonusReturn(L.meta, 6, pages[1]) || { col: landingNear(rows, wps[2].x + 24), top: 12 };
  // Same for the water room, off WaterArea1's own stream rather than the coin
  // room's — row $0e there names EntrancePage 7 for world 6, column 115, and a
  // pipe is standing at 115.
  const outw = waterReturn(L.meta, 6) || { col: landingNear(rows, wps[1].x + 24), top: 12 };
  const vine = L.meta.vine;
  const body = `
${bonusRoomSource('6-2b', 'WORLD 6-2', pages[0], back.col, back.top)}
${bonusRoomSource('6-2d', 'WORLD 6-2', pages[1], back2.col, back2.top, 'BONUS2')}
${waterRoomSource('6-2w', 'WORLD 6-2', outw.col, outw.top)}
${skyAreaSource('6-2c', 'WORLD 6-2', skyReturn(6, 'GroundArea21'), 'GroundArea21')}
export default {
  id: '6-2',
  name: 'WORLD 6-2',
  time: 400,
  theme: 'overworld',
  sky: 'night',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
    { x: ${vine.x}, y: ${vine.y}, item: 'vine', height: 11, warp: { to: { area: '6-2c', x: 3.5, y: 12, exit: 'none' } } },
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  warps: [
    { from: { x: ${wps[0].x}, y: ${wps[0].top} }, dir: 'down', to: { area: '6-2b', x: 3.5, y: 3, exit: 'down' } },
    { from: { x: ${wps[1].x}, y: ${wps[1].top} }, dir: 'down', to: { area: '6-2w', x: 2.5, y: 0, exit: 'none' } },
    { from: { x: ${wps[2].x}, y: ${wps[2].top} }, dir: 'down', to: { area: '6-2d', x: 3.5, y: 3, exit: 'down' } },
  ],
  areas: { '6-2b': BONUS, '6-2d': BONUS2, '6-2w': WATERROOM, '6-2c': SKY },
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '6-2.js'),
    header('6-2 — overworld, night', '// Colour control 4 — black sky, and NO palette write, so the foliage stays\n' +
        '// green. Twenty-eight pipes, three of them flagged as leading somewhere, and\n' +
        '// a beanstalk at ' + L.meta.vine.x + ' into coin heaven.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 6-3
{
  const L = emitLevel('6-3', { theme: 'overworld' });
  const rows = relieveBlocks(L.rows);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '6-3',
  name: 'WORLD 6-3',
  time: 300,
  theme: 'athletic',
  sky: 'night',
  tileset: 'castle',
  scenery: 'castle',
  music: 'overworld',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(L.entities)}
  ],
  flagpole: { x: ${L.meta.flagpole.x} },
  castle: { x: ${L.meta.castle.x} },
};
`;
  writeFileSync(
    join(OUT, '6-3.js'),
    header('6-3 — the lifts, night', '// Colour control 7. BGColorCtrl_Addr entry 7 is $04, and VRAM_AddrTable index\n' +
        '// 4 is CastlePaletteData — the FULL 32-byte palette, not the four-byte patch\n' +
        '// the snow levels get. So this is an overworld tile map drawn in the castle\n' +
        '// palette under a black sky, which is what `tileset: castle` asks for. The\n' +
        '// theme stays athletic, so props, particles and music are unaffected.\n' +
        '//\n' +
        '// The busiest lift level in the\n' +
        '// game: it is the only one that uses all four of our platform modes —\n' +
        '// vertical ($25), horizontal ($28), balance pairs ($24) and one that falls\n' +
        '// away under you ($29) — plus two jumpsprings.') + tilesBlock(rows) + body
  );
}

// ---------------------------------------------------------------------- 6-4
{
  const L = emitLevel('6-4', { theme: 'castle' });
  const ents = L.entities.slice();
  const rows = seatPodoboos(relieveBlocks(L.rows), ents);
  const sp = findSpawn(rows);
  const body = `
export default {
  id: '6-4',
  name: 'WORLD 6-4',
  time: 300,
  theme: 'castle',
  music: 'castle',
  width: ${L.width},
  height: 15,
  spawn: { x: ${sp.x}, y: ${sp.y} },
  tiles: TILES,
  contents: [
${contentsBlock(L.contents)}
  ],
  entities: [
${entsBlock(ents)}
  ],
  flagpole: null,
  castle: { x: ${L.width - 6}, tall: true },
};
`;
  writeFileSync(
    join(OUT, '6-4.js'),
    header('6-4 — castle', '// CastleArea1 — the SAME area as 1-4, tile for tile. Only the enemy stream\n' +
        '// differs, and most of THAT is hard-mode-only, so on a first quest this is a\n' +
        '// quieter 1-4 with the same lava and the same bridge.') + tilesBlock(rows) + body
  );
}

console.log('regenerated 6-1, 6-2, 6-3, 6-4 from reference data');
