// The carrier fighter, in the F6F Hellcat mould: deep radial cowling, bubble
// canopy over a visible pilot, mid wing, swept fin and a tailplane that clears
// the rudder. It is the sprite the player looks at every single frame, so it is
// the only one in this game authored at every attitude by hand.
//
// ROTATION. Turning here is a loop, so the aircraft is drawn at continuously
// varying angles. Rotating a pixel sprite off-axis — even with smoothing off —
// pulls thin features apart: at 45 degrees the one-pixel fin, the canopy frame
// and the prop disc all break into unconnected dots. So every attitude is drawn
// by hand instead. Thirteen frames cover -90 (vertical climb) through 0 (level)
// to +90 (vertical dive) in 15-degree steps, all right-facing; the renderer
// mirrors them for the leftward half of the loop. Fifteen degrees is roughly
// four ticks of the sim's turn rate, which is chunky in exactly the way a 1987
// sprite game is chunky, and every frame has hard edges because every frame was
// placed a pixel at a time.
//
// LAYOUT CONTRACT. Every frame is 32x32 and rotates about PLANE_PIVOT, which
// sits on the aircraft's centre of mass — mid-fuselage, on the thrust line. The
// nose therefore swings and the tail sweeps the opposite way, the way an
// aeroplane actually pitches, instead of the whole sprite orbiting its corner.
export const PLANE_W_ART = 32;
export const PLANE_H_ART = 32;
export const PLANE_PIVOT = { x: 15, y: 14 };

